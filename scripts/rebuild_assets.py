#!/usr/bin/env python3
"""Rebuild every terrain asset from its recipe and verify the result.

The terrain package in `assets/` is derived, not authored: contours, models,
previews and verification records all come from the recipes under
`assets/source/`.  This script is the reproduction entry point.  It

  1. runs the sample maker for all recipes (which re-runs the real CDT kernel),
  2. runs the verifier, which reconciles elevation error and constraint edges,
  3. confirms that no derived file drifted from what the recipes imply.

Run it after touching any recipe, and in CI.  `--check` only reports drift
without rewriting assets.

    python3 scripts/rebuild_assets.py
    python3 scripts/rebuild_assets.py --check
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, "assets")


def run(script, args, expect_ok=True):
    proc = subprocess.run([sys.executable, "-I", os.path.join(ROOT, "scripts", script)] + args,
                          cwd=ROOT, capture_output=True, text=True)
    if expect_ok and proc.returncode != 0:
        sys.stdout.write(proc.stdout)
        sys.stderr.write(proc.stderr)
        raise SystemExit("%s failed" % script)
    return proc


def snapshot():
    """Hashes of every derived asset file, keyed by relative path."""
    import hashlib
    hashes = {}
    for directory, _, names in os.walk(ASSETS):
        for name in sorted(names):
            path = os.path.join(directory, name)
            rel = os.path.relpath(path, ROOT)
            with open(path, "rb") as handle:
                hashes[rel] = hashlib.sha256(handle.read()).hexdigest()
    return hashes


def main(argv):
    parser = argparse.ArgumentParser(description="Rebuild and verify terrain assets")
    parser.add_argument("--check", action="store_true",
                        help="verify the current assets without regenerating them")
    args = parser.parse_args(argv)

    if args.check:
        before = snapshot()
        proc = run("verify_terrain_assets.py", [], expect_ok=False)
        sys.stdout.write(proc.stdout)
        after = snapshot()
        changed = sorted(k for k in before if before[k] != after.get(k))
        if changed:
            print("verification rewrote files: " + ", ".join(changed))
            return 1
        return proc.returncode

    before = snapshot()
    maker = run("make_terrain_assets.py", [])
    sys.stdout.write(maker.stdout)
    verifier = run("verify_terrain_assets.py", [], expect_ok=False)
    sys.stdout.write(verifier.stdout)
    after = snapshot()

    changed = sorted(k for k in set(before) | set(after) if before.get(k) != after.get(k))
    # The verification files are regenerated by design; anything else changing
    # means the maker is not reproducible.
    unexpected = [k for k in changed if not k.startswith("assets/verification/")]
    if unexpected:
        print("non-reproducible outputs changed: " + ", ".join(unexpected))
        return 1
    if verifier.returncode != 0:
        print("verification failed")
        return 1
    print("rebuild reproducible: %d files, none drifted unexpectedly" % len(after))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
